package snmpservermodel

import (
	"fmt"
	"strings"

	"gorm.io/gorm"
)

// ToConf renders d as a complete snmpd.conf. Every directive is omitted
// when its field is blank, since snmpd accepts a config with almost
// nothing in it but rejects a directive with a missing argument.
//
// Two orderings/pairings here are snmpd's rules, not style choices:
// "listen on" carries the protocol versions, and the enc half of the user
// line is only emitted alongside auth - snmpd rejects "enc" without
// "auth" ("auth is mandatory with enc"), so an enckey with no authkey is
// dropped rather than written out into a file that would fail its own
// check. Bind rejects that combination up front; this is the backstop for
// rows written straight to the DB.
func (d *SnmpServer) ToConf() string {
	var b strings.Builder
	if d.ListenIp != "" {
		fmt.Fprintf(&b, "listen on %s snmpv2c snmpv3\n", d.ListenIp)
	}
	if d.Community != "" {
		fmt.Fprintf(&b, "read-only community %q\n", d.Community)
	}
	if d.Username != "" {
		fmt.Fprintf(&b, "user %q", d.Username)
		if d.AuthKey != "" {
			fmt.Fprintf(&b, " auth hmac-sha256 authkey %q", d.AuthKey)
			if d.EncKey != "" {
				fmt.Fprintf(&b, " enc aes enckey %q", d.EncKey)
			}
		}
		b.WriteString("\n")
	}
	if d.SystemContact != "" {
		fmt.Fprintf(&b, "system contact %q\n", d.SystemContact)
	}
	if d.SystemDescription != "" {
		fmt.Fprintf(&b, "system description %q\n", d.SystemDescription)
	}
	if d.SystemLocation != "" {
		fmt.Fprintf(&b, "system location %q\n", d.SystemLocation)
	}
	if d.SystemServices > 0 {
		fmt.Fprintf(&b, "system services %d\n", d.SystemServices)
	}
	if d.SecLevel != "" {
		fmt.Fprintf(&b, "seclevel %s\n", d.SecLevel)
	}
	b.WriteString("filter-routes ")
	if d.FilterRoutes {
		b.WriteString("yes\n")
	} else {
		b.WriteString("no\n")
	}
	return b.String()
}

// GenerateConf renders snmpd.conf and returns it as text - used by the
// API's /conf view (UI preview) and by arkgated (config/pf.SnmpCreate),
// which fetches this same text over HTTP and stages it into its own
// rundir.
//
// Only the first record is rendered. snmpd.conf is one document, not a
// list of independent blocks the way dhcpd.conf's subnets are: "system
// location", "seclevel" and "filter-routes" are single global settings, so
// concatenating records would emit conflicting duplicates. The UI offers
// "New" only while the table is empty to match.
func GenerateConf(db *gorm.DB) (string, error) {
	var servers []SnmpServer
	if err := db.Order("id").Find(&servers).Error; err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	if len(servers) > 0 {
		b.WriteString(servers[0].ToConf())
	}
	return b.String(), nil
}
