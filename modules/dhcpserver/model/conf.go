package dhcpservermodel

import (
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/rbaylon/srvcman/database"
	"gorm.io/gorm"
)

// ToConf renders one dhcpd.conf "subnet { ... }" declaration for d.
// Subnet/Netmask/RangeStart/RangeEnd are always included since a subnet
// declaration requires them; every other option line is omitted when
// blank/zero so unset fields don't show up as empty dhcpd.conf directives.
func (d *DhcpServer) ToConf() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s (%s)\n", d.Name, d.Interface)
	fmt.Fprintf(&b, "subnet %s netmask %s {\n", d.Subnet, d.Netmask)
	fmt.Fprintf(&b, "\trange %s %s;\n", d.RangeStart, d.RangeEnd)
	if d.Routers != "" {
		fmt.Fprintf(&b, "\toption routers %s;\n", d.Routers)
	}
	if d.DomainName != "" {
		fmt.Fprintf(&b, "\toption domain-name \"%s\";\n", d.DomainName)
	}
	if d.DomainNameServers != "" {
		fmt.Fprintf(&b, "\toption domain-name-servers %s;\n", d.DomainNameServers)
	}
	if d.BroadcastAddress != "" {
		fmt.Fprintf(&b, "\toption broadcast-address %s;\n", d.BroadcastAddress)
	}
	if d.NtpServers != "" {
		fmt.Fprintf(&b, "\toption ntp-servers %s;\n", d.NtpServers)
	}
	if d.DefaultLeaseTime > 0 {
		fmt.Fprintf(&b, "\tdefault-lease-time %d;\n", d.DefaultLeaseTime)
	}
	if d.MaxLeaseTime > 0 {
		fmt.Fprintf(&b, "\tmax-lease-time %d;\n", d.MaxLeaseTime)
	}
	if d.NextServer != "" {
		fmt.Fprintf(&b, "\tnext-server %s;\n", d.NextServer)
	}
	if d.Filename != "" {
		fmt.Fprintf(&b, "\tfilename \"%s\";\n", d.Filename)
	}
	b.WriteString("}\n")
	return b.String()
}

// GenerateConf renders every DhcpServer row into one dhcpd.conf and stages
// it at RUN_DIR/dhcpd.conf - the same path modules/changes' PUT
// /changes/pending apply flow backs up/stages/reloads dhcpd from. The
// rendered text is always returned, even if the write fails, so callers
// (the API's /conf view) get a result reflecting the current DB state
// regardless of whether staging succeeded.
func GenerateConf(db *gorm.DB) (string, error) {
	var servers []DhcpServer
	if err := db.Find(&servers).Error; err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	for _, s := range servers {
		b.WriteString(s.ToConf())
		b.WriteString("\n")
	}
	conf := b.String()

	rundir := database.GetEnvVariable("RUN_DIR")
	if err := os.WriteFile(rundir+"dhcpd.conf", []byte(conf), 0640); err != nil {
		log.Println("dhcpserver: failed to stage dhcpd.conf:", err)
	}
	return conf, nil
}
