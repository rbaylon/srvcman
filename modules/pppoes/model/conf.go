package pppoemodel

import (
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/rbaylon/srvcman/database"
	"gorm.io/gorm"
)

// npppdAuth is npppd.conf's shared LOCAL authentication block. It doesn't
// vary per Pppoe row, so it's written once ahead of the per-tunnel blocks
// rather than modeled as a DB row.
const npppdAuth = `authentication LOCAL type local {
	users-file "/etc/npppd/npppd-users"
	user-max-session 1
}
`

// ToConf renders one npppd.conf tunnel/ipcp/interface/bind declaration set
// for d, keyed off d.DevIndex (the pppacN interface index assigned in
// Storage.Add).
func (d *Pppoe) ToConf() string {
	var b strings.Builder
	fmt.Fprintf(&b, "tunnel PPPOE%d protocol pppoe {\n", d.DevIndex)
	fmt.Fprintf(&b, "\tlisten on interface %s\n", d.Device)
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "ipcp IPCP%d {\n", d.DevIndex)
	fmt.Fprintf(&b, "\tpool-address %s\n", d.PoolAddress)
	fmt.Fprintf(&b, "\tdns-servers %s\n", d.DnsAddress)
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "interface pppac%d address %s ipcp IPCP%d\n", d.DevIndex, d.Ip, d.DevIndex)
	fmt.Fprintf(&b, "bind tunnel from PPPOE%d authenticated by LOCAL to pppac%d\n", d.DevIndex, d.DevIndex)
	return b.String()
}

// GenerateConf renders every Pppoe row into one npppd.conf and stages it at
// RUN_DIR/npppd.conf - the same staging pattern dhcpservermodel.GenerateConf
// and unbounddnsmodel.GenerateConf use, which modules/changes' PUT
// /changes/pending apply flow backs up/stages/restarts npppd from (into
// /etc/npppd/npppd.conf). The rendered text is always returned, even if the
// write fails, so callers (the API's /conf view) get a result reflecting
// the current DB state regardless of whether staging succeeded.
func GenerateConf(db *gorm.DB) (string, error) {
	var pppoes []Pppoe
	if err := db.Find(&pppoes).Error; err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	b.WriteString(npppdAuth)
	b.WriteString("\n")
	for _, p := range pppoes {
		b.WriteString(p.ToConf())
		b.WriteString("\n")
	}
	conf := b.String()

	rundir := database.GetEnvVariable("RUN_DIR")
	if err := os.WriteFile(rundir+"npppd.conf", []byte(conf), 0640); err != nil {
		log.Println("pppoes: failed to stage npppd.conf:", err)
	}
	return conf, nil
}
