package unbounddnsmodel

import (
	"fmt"
	"strings"

	"gorm.io/gorm"
)

// yesno renders an unbound.conf "yes"/"no" boolean option value.
func yesno(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// splitList splits a comma-separated field into trimmed, non-empty entries.
func splitList(s string) []string {
	parts := strings.Split(s, ",")
	out := make([]string, 0, len(parts))
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p != "" {
			out = append(out, p)
		}
	}
	return out
}

// ToConf renders d's "server:" block and, if it has a forward zone name or
// any forward-addr entries, its "forward-zone:" block.
func (d *UnboundDns) ToConf() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", d.Name)
	b.WriteString("server:\n")
	iface := d.Interface
	if iface == "" {
		iface = "0.0.0.0"
	}
	fmt.Fprintf(&b, "\tinterface: %s\n", iface)
	if d.TlsCertBundle != "" {
		fmt.Fprintf(&b, "\ttls-cert-bundle: \"%s\"\n", d.TlsCertBundle)
	}
	for _, ac := range splitList(d.AccessControl) {
		fmt.Fprintf(&b, "\taccess-control: %s\n", ac)
	}
	fmt.Fprintf(&b, "\tdo-not-query-localhost: %s\n", yesno(d.DoNotQueryLocalhost))
	fmt.Fprintf(&b, "\thide-identity: %s\n", yesno(d.HideIdentity))
	fmt.Fprintf(&b, "\thide-version: %s\n", yesno(d.HideVersion))
	fmt.Fprintf(&b, "\tprefetch: %s\n", yesno(d.Prefetch))
	for _, ld := range splitList(d.LocalData) {
		fmt.Fprintf(&b, "\tlocal-data: \"%s\"\n", ld)
	}

	forwardAddrs := splitList(d.ForwardAddr)
	if d.ForwardZoneName != "" || len(forwardAddrs) > 0 {
		zone := d.ForwardZoneName
		if zone == "" {
			zone = "."
		}
		b.WriteString("\nforward-zone:\n")
		fmt.Fprintf(&b, "\tname: \"%s\"\n", zone)
		fmt.Fprintf(&b, "\tforward-tls-upstream: %s\n", yesno(d.ForwardTlsUpstream))
		for _, fa := range forwardAddrs {
			fmt.Fprintf(&b, "\tforward-addr: %s\n", fa)
		}
	}
	return b.String()
}

// GenerateConf renders every UnboundDns row into one unbound.conf and
// returns it as text - used by the API's /conf view (UI preview) and by
// arkgated (config/pf.DnsCreate), which fetches this same text over HTTP
// and stages it into its own rundir. This no longer writes the file
// locally: srvcman and arkgated may run on separate hosts, so a file
// written to srvcman's own disk was never visible to arkgated's later
// mv/backup of that same path.
func GenerateConf(db *gorm.DB) (string, error) {
	var servers []UnboundDns
	if err := db.Find(&servers).Error; err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	for _, s := range servers {
		b.WriteString(s.ToConf())
		b.WriteString("\n")
	}
	return b.String(), nil
}
