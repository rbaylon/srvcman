package captiveportalmodel

import (
	"fmt"
	"strconv"
	"strings"

	"gorm.io/gorm"
)

// EnvPath is where the portal reads its configuration from, on the gateway.
const EnvPath = "/usr/local/arkgate/captiveportal/.env"

// ToConf renders c as the portal's .env file.
//
// Values are double-quoted because godotenv - which is what the portal
// parses this with - treats a quoted value as one token, so a value
// containing a space or '#' survives intact. Bind has already rejected
// quotes and newlines in these fields, which is what keeps a value from
// closing its own quote and appending env lines of its own.
func (c *CaptivePortal) ToConf() string {
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	for _, kv := range [][2]string{
		{"APP_IP", c.AppIp},
		{"APP_PORT", strconv.Itoa(c.AppPort)},
		{"API_URL", c.ApiUrl},
		{"API_AUTH", c.ApiAuth},
		{"ROUTER_ID", c.RouterId},
		{"ROUTER_INDEX", strconv.Itoa(c.RouterIndex)},
		{"UNIX_SOCK", c.UnixSock},
		{"ARKGATE_SOCKET", c.ArkgateSocket},
		{"ENABLED", strconv.FormatBool(c.Enabled)},
	} {
		fmt.Fprintf(&b, "%s=%q\n", kv[0], kv[1])
	}
	return b.String()
}

// GenerateConf renders the portal's .env and returns it as text - fetched
// over HTTP by arkgated, which writes it to EnvPath on the gateway.
//
// Only the first record is rendered: this is one app's config file, not a
// list of blocks, so the UI offers a single record.
//
// Unlike the other modules' /conf views this one is not safe to show in a
// browser - it contains API_AUTH, which is a working credential - so the
// UI has no preview of it and the endpoint exists for arkgated's benefit.
func GenerateConf(db *gorm.DB) (string, error) {
	var portals []CaptivePortal
	if err := db.Order("id").Find(&portals).Error; err != nil {
		return "", err
	}
	if len(portals) == 0 {
		return "", nil
	}
	return portals[0].ToConf(), nil
}
