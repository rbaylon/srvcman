package acmemodel

import (
	"fmt"
	"strings"

	"gorm.io/gorm"
)

// authorities is the fixed part of acme-client.conf: the Let's Encrypt
// production and staging endpoints. Neither is configurable through this
// module - the domain block below is the only part that varies - so they
// are a constant rather than model fields.
const authorities = `authority letsencrypt {
	api url "https://acme-v02.api.letsencrypt.org/directory"
	account key "/etc/acme/letsencrypt-privkey.pem"
}

authority letsencrypt-staging {
	api url "https://acme-staging-v02.api.letsencrypt.org/directory"
	account key "/etc/acme/letsencrypt-staging-privkey.pem"
}
`

// KeyPath is where acme-client writes the private key for fqdn, and
// FullChainPath the full chain certificate. Both are referenced from
// acme-client.conf and substituted into nginx.conf, so they are derived
// in one place rather than formatted at each use.
func KeyPath(fqdn string) string {
	return fmt.Sprintf("/etc/ssl/private/%s.key", fqdn)
}

func FullChainPath(fqdn string) string {
	return fmt.Sprintf("/etc/ssl/%s.fullchain.pem", fqdn)
}

// ToConf renders a's "domain { ... }" block.
func (a *Acme) ToConf() string {
	var b strings.Builder
	fmt.Fprintf(&b, "domain %s {\n", a.Fqdn)
	fmt.Fprintf(&b, "\tdomain key \"%s\"\n", KeyPath(a.Fqdn))
	fmt.Fprintf(&b, "\tdomain full chain certificate \"%s\"\n", FullChainPath(a.Fqdn))
	b.WriteString("\tsign with letsencrypt\n")
	b.WriteString("}\n")
	return b.String()
}

// GenerateConf renders acme-client.conf and returns it as text - used by
// the API's /conf view (UI preview) and by arkgated, which fetches this
// same text over HTTP and installs it at /etc/acme-client.conf.
//
// Only the first record is rendered, and only when it is enabled: this is
// a single-entry config, and a disabled record means "do not manage
// certificates", which is a config with no domain block rather than a
// domain block that happens not to be used.
func GenerateConf(db *gorm.DB) (string, error) {
	var acmes []Acme
	if err := db.Order("id").Find(&acmes).Error; err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# auto generated by arkgated, all manual edit will be overwritten\n\n")
	b.WriteString(authorities)
	if len(acmes) > 0 && acmes[0].Enabled {
		b.WriteString("\n")
		b.WriteString(acmes[0].ToConf())
	}
	return b.String(), nil
}

// Active returns the enabled record's FQDN, or "" when certificate
// management is off. arkgated calls the endpoint backed by this to learn
// what to pass to acme-client and what paths to point nginx at.
func Active(db *gorm.DB) (string, error) {
	var acmes []Acme
	if err := db.Order("id").Find(&acmes).Error; err != nil {
		return "", err
	}
	if len(acmes) == 0 || !acmes[0].Enabled {
		return "", nil
	}
	return acmes[0].Fqdn, nil
}
